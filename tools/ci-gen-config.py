#!/usr/bin/env python3
import json, os, sys, datetime

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hosts_env = os.environ.get("CHUMS_HUB_HOSTS", "")
hosts = [h.strip() for h in hosts_env.split(",") if h.strip()]
token = os.environ.get("CHUMS_WATCH_TOKEN", "")
if not hosts or not token:
    sys.exit("CHUMS_HUB_HOSTS and CHUMS_WATCH_TOKEN must be set before generating HubConfig.swift.")
diagnostics = os.environ.get("CHUMS_DIAGNOSTICS", "false").lower() in ("true", "1", "yes")

build = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
out = os.path.join(root, "app", "ChumsWatch", "HubConfig.swift")
os.makedirs(os.path.dirname(out), exist_ok=True)

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/ci-gen-config.py. Do not commit.\n")
    f.write("enum HubConfig {\n")
    f.write(f"    static let hosts = {json.dumps(hosts)}\n")
    f.write(f"    static let token = {json.dumps(token)}   // the watch's own token: the watch API only\n")
    f.write(f"    static let build = {json.dumps(build)}\n")
    f.write(f"    static let diagnostics = {'true' if diagnostics else 'false'}\n")
    f.write("}\n")

print(f"Generated {out} with hosts: {hosts}")
